"""
Вправа 3: "Виправ" — мутабельний спільний стан ламає ізоляцію.

Фікстура shared_cart має scope="module", тому це ОДИН список на весь модуль.
Обидва тести його мутують (append). Через це другий тест падає:
на момент його запуску кошик уже містить елемент з першого тесту.

Падіння ДЕТЕРМІНОВАНЕ: pytest виконує тести в порядку файлу, тож
test_add_first_item проходить, а test_cart_is_isolated падає завжди.

Крок 1: Запустіть файл — рівно один тест падає.
Крок 2: Прочитайте вивід і зрозумійте, чому.
Крок 3: Виправте фікстуру (див. блок ВІДПОВІДЬ нижче).

Запуск: pytest exercise_3_fix_practice.py -v
"""

import pytest


@pytest.fixture(scope="module")
def shared_cart():
    """АНТИ-ПАТЕРН: module-scope + мутабельний список, спільний для всіх тестів."""
    return []


def test_add_first_item(shared_cart):
    """Проходить: кошик порожній, додаємо один елемент."""
    shared_cart.append("book")
    assert len(shared_cart) == 1


def test_cart_is_isolated(shared_cart):
    """
    Падає: очікуємо свіжий кошик з одним елементом, але список уже містить
    "book" з попереднього тесту, тому довжина == 2, а не 1.
    """
    shared_cart.append("pen")
    assert len(shared_cart) == 1


# ВІДПОВІДЬ:
# Проблема: scope="module" робить список СПІЛЬНИМ для всіх тестів, а тести
# його мутують (append). Результат залежить від порядку — це порушення ізоляції.
#
# Виправлення: приберіть scope="module" (тобто зробіть фікстуру function-scope),
