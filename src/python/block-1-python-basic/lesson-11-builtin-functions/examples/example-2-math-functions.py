"""
Lesson 11: Example 2 - Math Functions
"""
numbers = [5, 2, 9, 1, 7, 3]
# sum() - сума
print("sum([5,2,9,1,7,3]) =", sum(numbers))
# min() - мінімум
print("min([5,2,9,1,7,3]) =", min(numbers))
# max() - максимум
print("max([5,2,9,1,7,3]) =", max(numbers))
# abs() - модуль
print("\nabs(-10) =", abs(-10))
print("abs(10) =", abs(10))
# round() - округлення
print("\nround(3.14159) =", round(3.14159))
print("round(3.14159, 2) =", round(3.14159, 2))
# pow() - степінь
print("\npow(2, 3) =", pow(2, 3))
print("2 ** 3 =", 2 ** 3)
