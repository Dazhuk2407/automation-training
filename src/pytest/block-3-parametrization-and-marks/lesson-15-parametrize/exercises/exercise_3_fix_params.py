import pytest


@pytest.mark.parametrize("n,expected", [(2, 4), (3, 8), (4, 16)])
def test_square(n, expected):
    """Квадрат числа. Один набір даних неправильний — знайдіть і виправте."""
    assert n * n == expected


@pytest.mark.parametrize("a,b,expected", [(2, 3, 5), (10, 5, 15), (0, 0, 0)])
def test_add(a, b, expected):
    """Ці набори даних правильні — тест має проходити повністю."""
    assert a + b == expected


@pytest.mark.parametrize("text,expected", [("hi", "HI"), ("PyTest", "PYTEST")])
def test_upper(text, expected):
    """Ці набори даних правильні — тест має проходити повністю."""
    assert text.upper() == expected


